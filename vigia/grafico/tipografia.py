SIN_TILDE = str.maketrans("ÁÉÍÓÚÜÑÀÈÌÒÙÂÊÎÔÛÇ", "AEIOUUNAEIOUAEIOUC")


def normalizar(texto: str) -> str:
    return texto.upper().translate(SIN_TILDE)


def ancho_texto(texto: str, escala: int, espaciado: int = 1) -> int:
    return len(normalizar(texto)) * (5 + espaciado) * escala


def escribir(
    lienzo: Lienzo,
    x: int,
    y: int,
    texto: str,
    color: Color,
    escala: int = 1,
    espaciado: int = 1,
    negrita: bool = False,
) -> int:
    """Dibuja el texto con la esquina superior izquierda en (x, y).

    `negrita` engorda el glifo repitiéndolo desplazado. Con una tipografía de
    mapa de bits es el único recurso para dar jerarquía a un titular, y a
    tamaño grande cuela perfectamente.
    """
    cursor = x
    grueso = max(1, escala // 3) if negrita else 0
    for caracter in normalizar(texto):
        glifo = GLIFOS.get(caracter)
        if glifo is None:
            cursor += (5 + espaciado) * escala
            continue
        for columna, bits in enumerate(glifo):
            for fila in range(7):
                if bits & (1 << fila):
                    lienzo.rect(
                        cursor + columna * escala,
                        y + fila * escala,
                        cursor + (columna + 1) * escala + grueso,
                        y + (fila + 1) * escala,
                        color,
                    )
        cursor += (5 + espaciado) * escala
    return cursor - x


def centrado(
    lienzo: Lienzo,
    centro_x: int,
    y: int,
    texto: str,
    color: Color,
    escala: int = 1,
    negrita: bool = False,
) -> None:
    escribir(
        lienzo,
        centro_x - ancho_texto(texto, escala) // 2,
        y,
        texto,
        color,
        escala,
        negrita=negrita,
    )
